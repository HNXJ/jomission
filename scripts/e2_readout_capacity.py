"""What the three-source readout can represent, independent of the spiking dynamics (reply to review 2, 2026-11-10).

Usage: python scripts/e2_readout_capacity.py OUT_JSON

Geometry only: 21 contacts (mf.CHANNELS), Gaussian kernel K_zu = exp(-(z - z_u)^2 / 2 sigma^2), unit depths S -0.4,
M 0, D 0.3. A source model gives contact power P_z = k_z^T C k_z for a source covariance C >= 0 (one frequency);
the scored quantity is R_z = P_z / max_z P_z. "mid" = mean of R over the contacts -0.2..0 (5 sampled contacts).
Target: the observed 50-150 Hz relative profile (PROTO), per frequency and band mean (mid 0.848).

Per sigma in 0.10..0.25:
  ceiling_3src: max over C >= 0 (3 x 3, cross terms allowed; C = L L^T, 64 starts, Nelder-Mead on the 6 entries
    of L) of mid; ceiling_C: the maximizing C as power shares and S-M, S-D, M-D coherences. single_M: the closed form for C = e_M e_M^T (sampled-contact mean of exp(-z^2/sigma^2)).
  fit_3src_auto: NNLS of the observed band-mean gamma profile on K^2 (3 sources, no cross terms) -> r with the
    target, mid of the normalized fit.
  fit_3src_full: least squares of the same profile on k^T C k, C >= 0 (64 starts) -> r, mid.
  fit_dist: the same profile on a distributed model, 41 sources at -0.6..0.4 (step 0.025), NNLS on K^2 ->
    r, mid. Positive control: the distributed model must reach the target (r >= 0.99).
  known_answer: the distributed fit's own profile is a target the distributed model represents exactly by
    construction; fit_3src_full is rerun on it, so a failure there is the three-source readout's, not a fitting
    failure (positive control: distributed refit residual < 1e-6 relative).
  self_recovery: a profile generated by a random C >= 0 on the three sources is refit by fit_3src_full
    (negative control for the optimizer: must reach r >= 0.999).
Signed lead fields, receptor-specific source depths and depth-dependent filtering are not modelled.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize, nnls

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e2_motif_figure as mf  # noqa: E402
import e2_scorer as sc  # noqa: E402

SIGMAS = (0.10, 0.15, 0.20, 0.25)
Z3 = np.array([-0.4, 0.0, 0.3])
ZD = np.round(np.arange(-0.6, 0.4 + 1e-9, 0.025), 3)
MID = (mf.CHANNELS >= -0.2 - 1e-9) & (mf.CHANNELS <= 0.0 + 1e-9)
GM = (sc.F >= 50) & (sc.F <= 150)
STARTS = 64


def kern(z: np.ndarray, s: float) -> np.ndarray:
    return np.exp(-((mf.CHANNELS[:, None] - z[None, :]) ** 2) / (2 * s ** 2))


def power(K: np.ndarray, L: np.ndarray) -> np.ndarray:
    """P_z = k_z^T L L^T k_z = |L^T k_z|^2."""
    return ((K @ L) ** 2).sum(axis=1)


def tril(x: np.ndarray, n: int) -> np.ndarray:
    L = np.zeros((n, n))
    L[np.tril_indices(n)] = x
    return L


def mid(P: np.ndarray) -> float:
    return float((P / P.max())[MID].mean())


def ceiling(K: np.ndarray, rng: np.random.Generator) -> tuple[float, dict]:
    """Max mid over C >= 0, and the maximizing C as power shares (diag / trace) and coherences."""
    def neg(x):
        P = power(K, tril(x, 3))
        return -mid(P) if P.max() > 0 else 0.0
    best, bx = 0.0, None
    for _ in range(STARTS):
        r = minimize(neg, rng.normal(size=6), method="Nelder-Mead", options={"xatol": 1e-9, "fatol": 1e-12,
                                                                             "maxiter": 6000})
        if -r.fun > best:
            best, bx = -r.fun, r.x
    L = tril(bx, 3)
    C = L @ L.T
    dg = np.sqrt(np.diag(C))
    coh = C / np.outer(dg, dg)
    return best, {"share": (np.diag(C) / np.trace(C)).round(4).tolist(),
                  "coh_SM": float(coh[0, 1]), "coh_SD": float(coh[0, 2]), "coh_MD": float(coh[1, 2])}


def fit_full(K: np.ndarray, y: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    def loss(x):
        return float(((power(K, tril(x, 3)) - y) ** 2).sum())
    best = None
    for _ in range(STARTS):
        r = minimize(loss, rng.normal(size=6), method="Nelder-Mead", options={"xatol": 1e-10, "fatol": 1e-14,
                                                                              "maxiter": 8000})
        if best is None or r.fun < best.fun:
            best = r
    return power(K, tril(best.x, 3))


def fit_nnls(K: np.ndarray, y: np.ndarray) -> np.ndarray:
    a, _ = nnls(K ** 2, y)
    return (K ** 2) @ a


def summary(P: np.ndarray, y: np.ndarray) -> dict:
    return {"r": float(np.corrcoef(P, y)[0, 1]), "mid": mid(P)}


def main(out: Path) -> None:
    rng = np.random.default_rng(20261110)
    y = sc.PROTO[:, GM].mean(axis=1)
    y = y / y.max()
    res = {"target_mid_bandmean": mid(y), "target_mid_mapmean": float(sc.PROTO[MID][:, GM].mean()),
           "contacts_mid": mf.CHANNELS[MID].tolist(), "starts": STARTS, "seed": 20261110, "sigma": {}}
    for s in SIGMAS:
        K3, KD = kern(Z3, s), kern(ZD, s)
        cmax, cC = ceiling(K3, rng)
        d = {"single_M": float(np.exp(-(mf.CHANNELS[MID] ** 2) / s ** 2).mean()), "ceiling_3src": cmax,
             "ceiling_C": cC}
        d["fit_3src_auto"] = summary(fit_nnls(K3, y), y)
        d["fit_3src_full"] = summary(fit_full(K3, y, rng), y)
        Pd = fit_nnls(KD, y)
        d["fit_dist"] = summary(Pd, y)
        Pd_re = fit_nnls(KD, Pd)
        d["known_answer"] = {"target_mid": mid(Pd), "dist_refit_rel_resid": float(np.linalg.norm(Pd_re - Pd) /
                                                                                   np.linalg.norm(Pd)),
                             "fit_3src_full": summary(fit_full(K3, Pd / Pd.max(), rng), Pd)}
        Pt = power(K3, tril(rng.normal(size=6), 3))
        d["self_recovery_r"] = summary(fit_full(K3, Pt / Pt.max(), rng), Pt)["r"]
        res["sigma"][f"{s:.2f}"] = d
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(res, indent=1))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
