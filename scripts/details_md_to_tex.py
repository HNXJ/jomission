"""Convert a W3 details file (<TAG>_details.md) to LaTeX tables for the paper.

Usage:
  python scripts/details_md_to_tex.py results/viz/paper_w3/<TAG>_details.md paper/jomission_lansa/tables/<TAG>_details.tex

Every markdown table under a '## <section>' heading becomes one booktabs tabular inside a table* float, captioned
with the section name. Cell text is escaped; values are copied, never recomputed. Prose lines are dropped.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
       "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "−": "$-$", "->": r"$\to$"}


def esc(s: str) -> str:
    s = s.strip().replace("`", "")
    out = re.sub("|".join(re.escape(k) for k in sorted(ESC, key=len, reverse=True)), lambda m: ESC[m.group(0)], s)
    return out


def tables(md: str) -> list[tuple[str, list[list[str]]]]:
    out, sec, rows = [], "", []
    for line in md.splitlines() + [""]:
        if line.startswith("## "):
            sec = line[3:].strip()
        if line.startswith("|"):
            cells = [c for c in line.strip().strip("|").split("|")]
            if not all(re.fullmatch(r"\s*:?-+:?\s*", c) for c in cells):
                rows.append(cells)
        elif rows:
            out.append((sec, rows))
            rows = []
    return out


def to_tex(tag: str, md: str) -> str:
    parts = [f"% Generated by scripts/details_md_to_tex.py from {tag}_details.md; do not edit by hand.\n"]
    # The Parameters longtable goes last: floats placed before it then keep their table numbers in page order.
    for sec, rows in sorted(tables(md), key=lambda t: t[0] == "Parameters"):
        ncol = len(rows[0])
        head = " & ".join(rf"\textbf{{{esc(c)}}}" for c in rows[0]) + r" \\"
        body = "\n".join(" & ".join(esc(c) for c in r) + r" \\" for r in rows[1:])
        if sec == "Parameters" and ncol == 5:  # long and wide: page-breaking longtable, wrapped columns
            parts.append(
                "\\clearpage\n{\\scriptsize\n\\begin{longtable}{lp{3.6cm}p{2.6cm}lp{6.2cm}}\n"
                f"\\caption{{{esc(tag)}: {esc(sec)}.}}\\\\\n\\toprule\n{head}\n\\midrule\n\\endfirsthead\n"
                f"\\toprule\n{head}\n\\midrule\n\\endhead\n\\bottomrule\n\\endlastfoot\n{body}\n"
                "\\end{longtable}}\n")
            continue
        spec = "l" * ncol
        parts.append(
            "\\begin{table}[p]\n\\centering\\scriptsize\n"
            f"\\caption{{{esc(tag)}: {esc(sec)}.}}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{head}\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n"
            "\\end{table}\n")
    return "\n".join(parts)


if __name__ == "__main__":
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    tag = src.name.removesuffix("_details.md")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(to_tex(tag, src.read_text(encoding="utf-8")), encoding="utf-8")
    print(dst, len(tables(src.read_text(encoding="utf-8"))), "tables")
