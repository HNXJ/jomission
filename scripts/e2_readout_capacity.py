"""What the three-source readout can represent, independent of the spiking dynamics (reply to review 2, 2026-11-10).

Usage: python scripts/e2_readout_capacity.py OUT_JSON

Geometry only: 21 contacts (mf.CHANNELS), Gaussian kernel K_zu = exp(-(z - z_u)^2 / 2 sigma^2), unit depths S -0.4,
M 0, D 0.3. A source model gives contact power P_z = k_z^T C k_z for a source covariance C >= 0 (one frequency, or
one covariance for a band-mean profile); the scored quantity is R_z = P_z / max_z P_z. "mid" = mean of R over the
five contacts -0.2..0.
Targets: map_mid = mean over 50-150 Hz and the mid contacts of the observed per-frequency relative map (0.848);
y = the observed 50-150 Hz band-mean profile divided by its maximum, the profile the scorer's r_gm correlates with.

Per sigma in 0.10..0.25:
  single_M: closed form for C = e_M e_M^T (mean of exp(-z^2/sigma^2) over the five mid contacts).
  ceiling_mid: max over C >= 0 (3 x 3, cross terms allowed; C = L L^T, STARTS Nelder-Mead starts on the 6 entries
    of L) of mid at one frequency, and the maximizing C as power shares and S-M, S-D, M-D coherences.
  maxr_full / maxr_auto: max over C >= 0 (full) or diagonal C (auto, no cross terms) of Pearson r(P, y), the
    scorer's r_gm statistic for one covariance across the band; the maximizer's mid and, for full, coherences.
  l2_full: the least-squares fit of y on k^T C k (r reported); kept to show that an L2 fit understates max r.
  dist: 41 sources at -0.6..0.4 (step 0.025), NNLS on K^2 -> r with y. A capacity check, not a validation: 41
    non-negative weights for 21 contacts.
Controls, asserted:
  self-recovery: 5 profiles generated by random C on the three sources; maxr_full must reach r >= 0.999 on each.
  negative: an alternating +1/0 profile over the 21 contacts (spacing 0.05, finer than every kernel width);
    maxr_full must stay below r = 0.5.
  order: maxr_full >= l2_full r and maxr_full >= maxr_auto (to 1e-9).
Signed lead fields, receptor-specific source depths and depth-dependent filtering are not modelled.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import minimize, nnls

sys.path.insert(0, str(Path(__file__).resolve().parent))
import e2_motif_figure as mf  # noqa: E402
import e2_scorer as sc  # noqa: E402

SIGMAS = (0.10, 0.15, 0.20, 0.25)
Z3 = np.array([-0.4, 0.0, 0.3])
ZD = np.round(np.arange(-0.6, 0.4 + 1e-9, 0.025), 3)
MID = (mf.CHANNELS >= -0.2 - 1e-9) & (mf.CHANNELS <= 0.0 + 1e-9)
GM = (sc.F >= 50) & (sc.F <= 150)
STARTS = 48
NM = {"xatol": 1e-10, "fatol": 1e-13, "maxiter": 8000}


def kern(z: np.ndarray, s: float) -> np.ndarray:
    return np.exp(-((mf.CHANNELS[:, None] - z[None, :]) ** 2) / (2 * s ** 2))


def power(K: np.ndarray, L: np.ndarray) -> np.ndarray:
    """P_z = k_z^T L L^T k_z = |L^T k_z|^2."""
    return ((K @ L) ** 2).sum(axis=1)


def tril(x: np.ndarray) -> np.ndarray:
    L = np.zeros((3, 3))
    L[np.tril_indices(3)] = x
    return L


def mid(P: np.ndarray) -> float:
    return float((P / P.max())[MID].mean())


def corr(P: np.ndarray, y: np.ndarray) -> float:
    return float(np.corrcoef(P, y)[0, 1]) if P.std() > 0 else -1.0


def describe(L: np.ndarray) -> dict:
    C = L @ L.T
    dg = np.sqrt(np.diag(C))
    coh = C / np.outer(dg, dg)
    return {"share": (np.diag(C) / np.trace(C)).round(4).tolist(),
            "coh_SM": float(coh[0, 1]), "coh_SD": float(coh[0, 2]), "coh_MD": float(coh[1, 2])}


def best_of(obj, n: int, rng: np.random.Generator) -> np.ndarray:
    """Minimize obj over R^n from STARTS random starts; return the best x."""
    best = None
    for _ in range(STARTS):
        r = minimize(obj, rng.normal(size=n), method="Nelder-Mead", options=NM)
        if best is None or r.fun < best.fun:
            best = r
    return best.x


def ceiling_mid(K: np.ndarray, rng: np.random.Generator) -> dict:
    x = best_of(lambda v: -mid(power(K, tril(v))) if power(K, tril(v)).max() > 0 else 0.0, 6, rng)
    L = tril(x)
    return {"mid": mid(power(K, L)), **describe(L)}


def maxr_full(K: np.ndarray, y: np.ndarray, rng: np.random.Generator) -> dict:
    L = tril(best_of(lambda v: -corr(power(K, tril(v)), y), 6, rng))
    P = power(K, L)
    return {"r": corr(P, y), "mid": mid(P), **describe(L)}


def maxr_auto(K: np.ndarray, y: np.ndarray, rng: np.random.Generator) -> dict:
    a = best_of(lambda v: -corr((K ** 2) @ (v ** 2), y), 3, rng) ** 2
    P = (K ** 2) @ a
    return {"r": corr(P, y), "mid": mid(P), "share": (a / a.sum()).round(4).tolist()}


def l2_full(K: np.ndarray, y: np.ndarray, rng: np.random.Generator) -> float:
    x = best_of(lambda v: float(((power(K, tril(v)) - y) ** 2).sum()), 6, rng)
    return corr(power(K, tril(x)), y)


def main(out: Path) -> None:
    rng = np.random.default_rng(20261110)
    y = sc.PROTO[:, GM].mean(axis=1)
    y = y / y.max()
    neg = (np.arange(mf.CHANNELS.size) % 2).astype(float)
    res = {"map_mid": float(sc.PROTO[MID][:, GM].mean()), "y_mid": mid(y), "contacts_mid": mf.CHANNELS[MID].tolist(),
           "starts": STARTS, "seed": 20261110, "sigma": {}}
    for s in SIGMAS:
        K3, KD = kern(Z3, s), kern(ZD, s)
        a, _ = nnls(KD ** 2, y)
        d = {"single_M": float(np.exp(-(mf.CHANNELS[MID] ** 2) / s ** 2).mean()),
             "ceiling_mid": ceiling_mid(K3, rng), "maxr_full": maxr_full(K3, y, rng),
             "maxr_auto": maxr_auto(K3, y, rng), "l2_full_r": l2_full(K3, y, rng),
             "dist": {"r": corr((KD ** 2) @ a, y), "mid": mid((KD ** 2) @ a)}}
        rec = []
        for _ in range(5):
            Pt = power(K3, tril(rng.normal(size=6)))
            rec.append(maxr_full(K3, Pt / Pt.max(), rng)["r"])
        d["self_recovery_r"] = rec
        d["negative_r"] = maxr_full(K3, neg, rng)["r"]
        assert min(rec) >= 0.999, f"self-recovery failed at sigma {s}: {rec}"
        assert d["negative_r"] < 0.5, f"negative control reached r {d['negative_r']} at sigma {s}"
        assert d["maxr_full"]["r"] >= d["l2_full_r"] - 1e-9 and d["maxr_full"]["r"] >= d["maxr_auto"]["r"] - 1e-9
        res["sigma"][f"{s:.2f}"] = d
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(res, indent=1))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
